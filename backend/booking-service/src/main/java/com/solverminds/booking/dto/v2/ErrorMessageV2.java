package com.solverminds.booking.dto.v2;

import io.swagger.v3.oas.annotations.media.Schema;
import java.util.ArrayList;
import java.util.List;

/**
 * RFC 7807 Problem Details error response for V2 API.
 */
@Schema(name = "ErrorMessage", description = "Details about an error that occurred")
public class ErrorMessageV2 {

    @Schema(description = "A human-readable explanation specific to this occurrence of the problem",
            required = true,
            example = "User data validation failed. Please review the provided data.")
    private String detail;

    @Schema(description = "A short, human-readable summary of the problem type",
            example = "Validation Failed")
    private String title;

    @Schema(description = "The HTTP status code generated by the origin server for this occurrence of the problem",
            example = "400")
    private Integer status;

    @Schema(description = "A URI reference that identifies the problem type",
            example = "https://example.com/probs/validation-failed")
    private String type;

    @Schema(description = "A URI reference that identifies the specific occurrence of the problem",
            example = "/user/12345/validate")
    private String instance;

    @Schema(description = "An API specific error code aiding the provider team to understand the error",
            example = "VALIDATION_FAILED")
    private String code;

    @Schema(description = "An array of error details to accompany a problem details response")
    private List<NestedErrorMessageV2> errors;

    public ErrorMessageV2() {
        this.errors = new ArrayList<>();
    }

    public ErrorMessageV2(String detail) {
        this.detail = detail;
        this.errors = new ArrayList<>();
    }

    public ErrorMessageV2(String detail, String title, Integer status) {
        this.detail = detail;
        this.title = title;
        this.status = status;
        this.errors = new ArrayList<>();
    }

    /**
     * Factory method for Bad Request errors
     */
    public static ErrorMessageV2 badRequest(String detail) {
        ErrorMessageV2 error = new ErrorMessageV2(detail, "Bad Request", 400);
        error.setCode("BAD_REQUEST");
        return error;
    }

    /**
     * Factory method for Unauthorized errors
     */
    public static ErrorMessageV2 unauthorized(String detail) {
        ErrorMessageV2 error = new ErrorMessageV2(detail, "Unauthorized", 401);
        error.setCode("UNAUTHORIZED");
        return error;
    }

    /**
     * Factory method for Forbidden errors
     */
    public static ErrorMessageV2 forbidden(String detail) {
        ErrorMessageV2 error = new ErrorMessageV2(detail, "Forbidden", 403);
        error.setCode("FORBIDDEN");
        return error;
    }

    /**
     * Factory method for Not Found errors
     */
    public static ErrorMessageV2 notFound(String detail) {
        ErrorMessageV2 error = new ErrorMessageV2(detail, "Not Found", 404);
        error.setCode("NOT_FOUND");
        return error;
    }

    /**
     * Factory method for Conflict errors
     */
    public static ErrorMessageV2 conflict(String detail) {
        ErrorMessageV2 error = new ErrorMessageV2(detail, "Conflict", 409);
        error.setCode("CONFLICT");
        return error;
    }

    /**
     * Factory method for Internal Server errors
     */
    public static ErrorMessageV2 internalServerError(String detail) {
        ErrorMessageV2 error = new ErrorMessageV2(detail, "Internal Server Error", 500);
        error.setCode("INTERNAL_SERVER_ERROR");
        return error;
    }

    /**
     * Factory method for Service Unavailable errors
     */
    public static ErrorMessageV2 serviceUnavailable(String detail) {
        ErrorMessageV2 error = new ErrorMessageV2(detail, "Service Unavailable", 503);
        error.setCode("SERVICE_UNAVAILABLE");
        return error;
    }

    /**
     * Add a nested error detail
     */
    public ErrorMessageV2 addNestedError(NestedErrorMessageV2 nestedError) {
        if (this.errors == null) {
            this.errors = new ArrayList<>();
        }
        this.errors.add(nestedError);
        return this;
    }

    /**
     * Add a nested error detail with convenience parameters
     */
    public ErrorMessageV2 addNestedError(String detail, String pointer, String code) {
        return addNestedError(new NestedErrorMessageV2(detail, pointer, code));
    }

    // Getters and Setters

    public String getDetail() {
        return detail;
    }

    public void setDetail(String detail) {
        this.detail = detail;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public Integer getStatus() {
        return status;
    }

    public void setStatus(Integer status) {
        this.status = status;
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }

    public String getInstance() {
        return instance;
    }

    public void setInstance(String instance) {
        this.instance = instance;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public List<NestedErrorMessageV2> getErrors() {
        return errors;
    }

    public void setErrors(List<NestedErrorMessageV2> errors) {
        this.errors = errors;
    }
}

