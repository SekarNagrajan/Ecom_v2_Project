package com.svm.ecom.dto;

import com.fasterxml.jackson.annotation.JsonInclude;
import io.swagger.v3.oas.annotations.media.Schema;

import java.util.ArrayList;
import java.util.List;

/**
 * Error response body for V2 APIs (client request standard).
 * Matches OpenAPI schema ErrorMessage: detail, title, status, type, instance, code, errors.
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
@Schema(name = "ErrorMessage", description = "Details about an error that occurred. Required: detail.",
        example = "{\"detail\":\"Customer data validation failed. Please review the provided data.\",\"title\":\"Validation Failed\",\"status\":400,\"instance\":\"/api/v2/master/customers\",\"code\":\"VALIDATION_FAILED\",\"errors\":[{\"detail\":\"The email address does not match the required format.\",\"pointer\":\"#/email\",\"code\":\"INVALID_EMAIL_FORMAT\"}]}")
public class ErrorMessage {

    @Schema(description = "A human-readable explanation specific to this occurrence of the problem", requiredMode = Schema.RequiredMode.REQUIRED)
    private String detail;

    @Schema(description = "A short, human-readable summary of the problem type. It should not change from occurrence to occurrence of the problem, except for localization purposes.")
    private String title;

    @Schema(description = "The HTTP status code generated by the origin server for this occurrence of the problem", type = "integer", example = "400")
    private Integer status;

    @Schema(description = "A URI reference that identifies the problem type. This URI should provide human-readable documentation for the problem type when dereferenced", hidden = true)
    private String type;

    @Schema(description = "A URI reference that identifies the specific occurrence of the problem. It may or may not yield further information if dereferenced")
    private String instance;

    @Schema(description = "An API specific error code aiding the provider team to understand the error based on their own taxonomy or registry")
    private String code;

    @Schema(description = "An array of error details to accompany a problem details response. Each item is an object that provides explicit details on a problem towards an API consumer")
    private List<NestedErrorMessage> errors;

    public ErrorMessage() {}

    public ErrorMessage(String detail, String title, Integer status, String type, String instance, String code) {
        this.detail = detail;
        this.title = title;
        this.status = status;
        this.type = type;
        this.instance = instance;
        this.code = code;
    }

    public String getDetail() { return detail; }
    public void setDetail(String detail) { this.detail = detail; }
    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }
    public Integer getStatus() { return status; }
    public void setStatus(Integer status) { this.status = status; }
    public String getType() { return type; }
    public void setType(String type) { this.type = type; }
    public String getInstance() { return instance; }
    public void setInstance(String instance) { this.instance = instance; }
    public String getCode() { return code; }
    public void setCode(String code) { this.code = code; }
    public List<NestedErrorMessage> getErrors() { return errors; }
    public void setErrors(List<NestedErrorMessage> errors) { this.errors = errors != null ? errors : new ArrayList<>(); }
}
