package com.solverminds.sibl.dto.v2;

import io.swagger.v3.oas.annotations.media.Schema;
import java.util.ArrayList;
import java.util.List;

@Schema(description = "Details about an error that occurred")
public class ErrorMessage {

    @Schema(description = "A human-readable explanation specific to this occurrence of the problem",
            requiredMode = Schema.RequiredMode.REQUIRED)
    private String detail;

    @Schema(description = "A short, human-readable summary of the problem type")
    private String title;

    @Schema(description = "The HTTP status code generated by the origin server for this occurrence of the problem")
    private Integer status;

    @Schema(description = "A URI reference that identifies the problem type")
    private String type;

    @Schema(description = "URI of this specific error occurrence")
    private String instance;

    @Schema(description = "An API specific error code aiding the provider team to understand the error")
    private String code;

    @Schema(description = "An array of error details to accompany a problem details response")
    private List<NestedErrorMessage> errors;

    public ErrorMessage() {
        this.errors = new ArrayList<>();
    }

    public ErrorMessage(String detail, String title, Integer status) {
        this.detail = detail;
        this.title = title;
        this.status = status;
        this.errors = new ArrayList<>();
    }

    public static ErrorMessage unauthorized(String detail) {
        ErrorMessage error = new ErrorMessage(detail, "Unauthorized", 401);
        error.setCode("UNAUTHORIZED");
        return error;
    }

    public static ErrorMessage forbidden(String detail) {
        ErrorMessage error = new ErrorMessage(detail, "Forbidden", 403);
        error.setCode("FORBIDDEN");
        return error;
    }

    public static ErrorMessage notFound(String detail) {
        ErrorMessage error = new ErrorMessage(detail, "Not Found", 404);
        error.setCode("NOT_FOUND");
        return error;
    }

    public static ErrorMessage internalServerError(String detail) {
        ErrorMessage error = new ErrorMessage(detail, "Internal Server Error", 500);
        error.setCode("INTERNAL_SERVER_ERROR");
        return error;
    }

    public static ErrorMessage serviceUnavailable(String detail) {
        ErrorMessage error = new ErrorMessage(detail, "Service Unavailable", 503);
        error.setCode("SERVICE_UNAVAILABLE");
        return error;
    }

    public ErrorMessage addNestedError(String detail, String pointer, String code) {
        if (this.errors == null) {
            this.errors = new ArrayList<>();
        }
        this.errors.add(new NestedErrorMessage(detail, pointer, code));
        return this;
    }

    public String getDetail() { return detail; }
    public void setDetail(String detail) { this.detail = detail; }

    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }

    public Integer getStatus() { return status; }
    public void setStatus(Integer status) { this.status = status; }

    public String getType() { return type; }
    public void setType(String type) { this.type = type; }

    public String getInstance() { return instance; }
    public void setInstance(String instance) { this.instance = instance; }

    public String getCode() { return code; }
    public void setCode(String code) { this.code = code; }

    public List<NestedErrorMessage> getErrors() { return errors; }
    public void setErrors(List<NestedErrorMessage> errors) { this.errors = errors; }
}
